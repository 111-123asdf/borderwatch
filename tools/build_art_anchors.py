"""Read-only PNG analysis; writes GDScript anchor metadata, never edits raster assets."""
from pathlib import Path
from statistics import median
from PIL import Image
root = Path(__file__).resolve().parents[1]
bank={}
for p in (root/'assets/v06').glob('*.png'):
    key=p.stem
    if 'portrait' in key or 'lineup' in key or 'map_' in key: continue
    cols,rows=(4,3) if key=='towers' else (4,2) if key=='props' else (6,3) if key.startswith('creature_') else (6,7)
    im=Image.open(p).convert('RGBA');w,h=im.size
    def foot(x,y):
        cell=im.crop((round(x*w/cols),round(y*h/rows),round((x+1)*w/cols),round((y+1)*h/rows)))
        bounds=cell.getchannel('A').point(lambda a:255 if a>100 else 0).getbbox()
        return round(bounds[3]/cell.height,5) if bounds else 0.9
    if key=='towers':
        for x,kind in enumerate(['archer','mage','cannon','barracks']):
            for y in range(3):bank[f'tower_{kind}_{y+1}']=foot(x,y)
    elif key=='props':
        for i in range(8):bank[f'prop_{i}']=foot(i%4,i//4)
    else:bank[key]=round(median(foot(x,0) for x in range(6)),5)
lines=['class_name ArenaArtAnchors','extends RefCounted','# Generated by tools/build_art_anchors.py from final transparent PNG bounds.','const FEET := {']
lines += [f'\t"{k}":{v},' for k,v in sorted(bank.items())]
lines+=['}','static func offset_for(key: String) -> float: return float(FEET.get(key,0.9))-0.5','']
(root/'scripts/arena/arena_art_anchors.gd').write_text('\n'.join(lines),encoding='utf-8')
print('ANCHORS',len(bank))
